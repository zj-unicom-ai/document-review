"""汇总平台与 core 运行时依赖并生成带 hash 的通用锁文件。"""

from __future__ import annotations

import argparse
import difflib
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "requirements.in"
OUTPUT = ROOT / "requirements.lock"
LOCAL_PACKAGES = {"document-review", "document-review-core"}
# 锁文件复现截止时间：显式升级时通过 --cutoff 更新，不能让新发布包悄悄进入构建。
DEFAULT_CUTOFF = "2026-10-21T08:30:00Z"
BUILD_REQUIREMENTS = ("setuptools>=68", "wheel")
# 显式固定 fork 策略与目标 Python 版本，避免 macOS / Linux uv 输出漂移。
LOCK_FORK_STRATEGY = "requires-python"
LOCK_PYTHON_VERSION = "3.12.16"


def _runtime_requirements() -> list[str]:
    """合并根包与 core 包的外部运行时依赖，本地包由源码安装不进锁。"""
    items: list[str] = []
    for relative in ("pyproject.toml", "packages/core/pyproject.toml"):
        data = tomllib.loads((ROOT / relative).read_text(encoding="utf-8"))
        for item in data["project"]["dependencies"]:
            name = Requirement(item).name
            if name.lower().replace("_", "-") in LOCAL_PACKAGES:
                continue
            if item not in items:
                items.append(item)
    if not items:
        raise RuntimeError("未找到任何外部运行时依赖")
    return items


def _lock_requirements() -> list[str]:
    """运行时依赖加本地 editable 构建所需的最小构建工具。"""
    return [*_runtime_requirements(), *BUILD_REQUIREMENTS]


def _write_input() -> None:
    lines = [
        "# 由 scripts/compile_python_lock.py 生成；请勿手工编辑。",
        "# 包含根包与 document-review-core 的运行时依赖及源码构建工具。",
        *_lock_requirements(),
        "",
    ]
    INPUT.write_text("\n".join(lines), encoding="utf-8")


def _uv() -> str:
    executable = shutil.which("uv")
    if executable is None:
        raise RuntimeError("生成锁文件需要安装 uv：https://docs.astral.sh/uv/")
    return executable


def _compile(
    input_path: Path,
    output_path: Path,
    *,
    upgrade: bool,
    cutoff: str,
) -> None:
    command = [
        _uv(),
        "pip",
        "compile",
        "--quiet",
        "--universal",
        "--generate-hashes",
        "--no-annotate",
        f"--exclude-newer={cutoff}",
        f"--fork-strategy={LOCK_FORK_STRATEGY}",
        f"--python-version={LOCK_PYTHON_VERSION}",
        "-o",
        str(output_path),
        str(input_path),
    ]
    if upgrade:
        command.append("--upgrade")
    subprocess.run(command, check=True, cwd=ROOT)
    _normalize_header(output_path, cutoff=cutoff)


def _normalize_header(path: Path, *, cutoff: str) -> None:
    """将 autogenerated 命令中的本机绝对路径规范成仓库相对路径。"""
    lines = path.read_text(encoding="utf-8").splitlines()
    if len(lines) < 2 or not lines[0].startswith("# This file"):
        return
    lines[1] = (
        "#    uv pip compile --quiet --universal --generate-hashes --no-annotate "
        f"--exclude-newer={cutoff} --fork-strategy={LOCK_FORK_STRATEGY} "
        f"--python-version={LOCK_PYTHON_VERSION} -o requirements.lock requirements.in"
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _lock_body(path: Path) -> str:
    """去掉 autogenerated 命令头后比较锁内容，避免临时路径造成误差。"""
    lines = path.read_text(encoding="utf-8").splitlines()
    return "\n".join(lines[2:]) + "\n"


def check(*, upgrade: bool = False, cutoff: str) -> int:
    """重新解析锁并与当前文件比较，防止 pyproject 与 lock 漂移。"""
    expected_input = "\n".join(
        [
            "# 由 scripts/compile_python_lock.py 生成；请勿手工编辑。",
            "# 包含根包与 document-review-core 的运行时依赖及源码构建工具。",
            *_lock_requirements(),
            "",
        ]
    )
    if INPUT.read_text(encoding="utf-8") != expected_input:
        print("requirements.in 与 pyproject 运行时依赖不一致", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory(prefix="document-review-lock-") as directory:
        temp_root = Path(directory)
        temp_input = temp_root / "requirements.in"
        temp_output = temp_root / "requirements.lock"
        temp_input.write_text(INPUT.read_text(encoding="utf-8"), encoding="utf-8")
        _compile(temp_input, temp_output, upgrade=upgrade, cutoff=cutoff)
        if _lock_body(temp_output) != _lock_body(OUTPUT):
            diff = "\n".join(
                difflib.unified_diff(
                    _lock_body(OUTPUT).splitlines(),
                    _lock_body(temp_output).splitlines(),
                    fromfile="requirements.lock",
                    tofile="resolved requirements",
                )
            )
            print(diff, file=sys.stderr)
            return 1
    print("Python 依赖锁检查通过")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="生成 Python 运行时依赖锁")
    parser.add_argument("--check", action="store_true", help="校验当前锁是否可复现")
    parser.add_argument("--upgrade", action="store_true", help="允许解析新版本")
    parser.add_argument("--cutoff", default=DEFAULT_CUTOFF, help="依赖解析截止时间")
    args = parser.parse_args()
    if args.check:
        return check(upgrade=args.upgrade, cutoff=args.cutoff)
    _write_input()
    _compile(INPUT, OUTPUT, upgrade=args.upgrade, cutoff=args.cutoff)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
